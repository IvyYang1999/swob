export type CatalogLocale = keyof typeof catalogTranslationContribution.locales
export type CatalogTranslationKey = keyof typeof catalogTranslationContribution.locales.en

export const CATALOG_COMPONENT_TRANSLATION_KEYS = [...catalogTranslationContribution.ownedKeys] as const

export function translateCatalog(locale: CatalogLocale, key: CatalogTranslationKey, params: Record<string, string | number> = {}): string {
  const messages = catalogTranslationContribution.locales[locale] || catalogTranslationContribution.locales.en
  let value: string = messages[key]
  for (const [name, replacement] of Object.entries(params)) value = value.replaceAll(`{${name}}`, String(replacement))
  return value
}
