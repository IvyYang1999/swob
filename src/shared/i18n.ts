export function resolveSystemLocale(preferredLanguages: readonly string[]): Locale {
  const primaryLanguage = preferredLanguages.find((language) => language.trim().length > 0)
  return primaryLanguage?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

export function resolveConfiguredLocale(
  configuredLocale: unknown,
  systemLocale: Locale
): Locale {
  if (configuredLocale === 'zh-CN' || configuredLocale === 'en') return configuredLocale
  // A legacy Japanese preference must not fall back to the partial skeleton.
  if (configuredLocale === 'ja') return 'en'
  return systemLocale
}

/**
 * Translate a key with optional interpolation.
 * Usage: t('sidebar.days_ago', { n: 3 }) → "3天前" or "3d ago"
 */
export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let text = translations[locale]?.[key] || translations['en']?.[key] || key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return text
}

